import { afterAll, beforeAll, describe, expect, it } from "vitest";
import { addMember, asAdmin, asAnon, asService, asUser, closePool, count, createOrg, createUser, pgError } from "./helpers";

afterAll(closePool);

type U = { id: string; email: string };

const submit = (token: string, payload: Record<string, unknown>, kind = "form", ipHash: string | null = null, spam = false) =>
  asService(async (q) => {
    const res = await q<{ result: { status: string; lead_id?: string } }>(
      "select public.intake_submit($1, $2, $3, $4, null, $5) as result",
      [token, kind, JSON.stringify(payload), ipHash, spam],
    );
    return res.rows[0].result;
  });

describe("lead intake (forms and webhooks)", () => {
  let owner: U, member: U;
  let org: string;
  let sourceId: string;
  let form: { id: string; token: string };
  let webhook: { id: string; token: string };

  beforeAll(async () => {
    owner = await createUser("owner");
    org = await createOrg(owner.id);
    member = await addMember(org, owner.id, "member", "member");
    sourceId = await asAdmin(async (q) =>
      (await q<{ id: string }>("select id from public.lead_sources where organization_id = $1 and kind = 'form'", [org])).rows[0].id,
    );
    await asUser(owner.id, async (q) => {
      form = (
        await q<{ id: string; token: string }>(
          "insert into public.forms (organization_id, name, source_id, owner_id) values ($1, 'טופס באתר', $2, $3) returning id, token",
          [org, sourceId, member.id],
        )
      ).rows[0];
      webhook = (
        await q<{ id: string; token: string }>(
          "insert into public.forms (organization_id, kind, name) values ($1, 'webhook', 'Zapier') returning id, token",
          [org],
        )
      ).rows[0];
    });
  });

  it("the token is generated by the database: 32 hex characters, and a client cannot set or change it", async () => {
    expect(form.token).toMatch(/^[0-9a-f]{32}$/);
    const set = await pgError(
      asUser(owner.id, (q) => q("insert into public.forms (organization_id, name, token) values ($1, 'x', 'chosen-token')", [org])),
    );
    expect(set.code).toBe("42501");
    const change = await pgError(asUser(owner.id, (q) => q("update public.forms set token = 'x' where id = $1", [form.id])));
    expect(change.code).toBe("42501");
  });

  it("a submission creates a lead with the form's source and owner, and logs the submission", async () => {
    const result = await submit(form.token, { full_name: "  נועה כהן ", phone: "052-1112233", email: "Noa@Example.com", message: "מעוניינת" });
    expect(result.status).toBe("accepted");
    const lead = await asAdmin(async (q) =>
      (
        await q<{ full_name: string; email: string; source_id: string; owner_id: string; phone_e164: string; status_kind: string }>(
          `select l.full_name, l.email, l.source_id, l.owner_id, l.phone_e164, s.kind as status_kind
             from public.leads l join public.lead_statuses s on s.id = l.status_id where l.id = $1`,
          [result.lead_id],
        )
      ).rows[0],
    );
    expect(lead).toMatchObject({ full_name: "נועה כהן", email: "noa@example.com", source_id: sourceId, owner_id: member.id, phone_e164: "+972521112233", status_kind: "open" });
    expect(await asAdmin((q) => count(q, "select 1 from public.form_submissions where lead_id = $1 and status = 'accepted'", [result.lead_id]))).toBe(1);
    // the assignee is told
    expect(await asAdmin((q) => count(q, "select 1 from public.notifications where user_id = $1 and entity_id = $2", [member.id, result.lead_id]))).toBe(1);
  });

  it("required fields, identity and email format are checked", async () => {
    expect((await pgError(submit(form.token, { full_name: "בלי טלפון" }))).code).toBe("22023");
    expect((await pgError(submit(webhook.token, { company_name: "רק חברה" }, "webhook"))).code).toBe("22023");
    expect((await pgError(submit(webhook.token, { email: "not-an-email" }, "webhook"))).code).toBe("22023");
    // a webhook has no required-field list: any one of name / phone / email is enough
    expect((await submit(webhook.token, { email: "lead@example.com" }, "webhook")).status).toBe("accepted");
  });

  it("a token only works for its own kind, and an inactive form accepts nothing", async () => {
    expect((await pgError(submit(form.token, { phone: "050-1" }, "webhook"))).code).toBe("P0002");
    expect((await pgError(submit(webhook.token, { phone: "050-1" }, "form"))).code).toBe("P0002");
    expect((await pgError(submit("0".repeat(32), { phone: "050-1" }))).code).toBe("P0002");

    await asUser(owner.id, (q) => q("update public.forms set is_active = false where id = $1", [webhook.id]));
    expect((await pgError(submit(webhook.token, { phone: "050-1234567" }, "webhook"))).code).toBe("P0002");
    await asUser(owner.id, (q) => q("update public.forms set is_active = true where id = $1", [webhook.id]));
  });

  it("spam is logged without a lead, and one sender is rate limited", async () => {
    const before = await asAdmin((q) => count(q, "select 1 from public.leads where organization_id = $1", [org]));
    expect((await submit(form.token, { full_name: "בוט", phone: "1" }, "form", "spam-ip", true)).status).toBe("spam");
    expect(await asAdmin((q) => count(q, "select 1 from public.leads where organization_id = $1", [org]))).toBe(before);

    // ten in ten minutes are fine, the eleventh is refused
    for (let i = 0; i < 10; i++) {
      await submit(form.token, { full_name: `פונה ${i}`, phone: "050-0000000" }, "form", "busy-ip");
    }
    const limited = await pgError(submit(form.token, { full_name: "עוד אחד", phone: "050-0000000" }, "form", "busy-ip"));
    expect(limited.code).toBe("P0001");
    expect(limited.hint).toBe("rate_limited");
    // another sender is not affected
    expect((await submit(form.token, { full_name: "שולח אחר", phone: "050-0000001" }, "form", "other-ip")).status).toBe("accepted");
  });

  it("only the server can submit: anon and signed-in users cannot call intake_submit", async () => {
    const anon = await pgError(asAnon((q) => q("select public.intake_submit($1, 'form', '{}')", [form.token])));
    expect(anon.code).toBe("42501");
    const user = await pgError(asUser(owner.id, (q) => q("select public.intake_submit($1, 'form', '{}')", [form.token])));
    expect(user.code).toBe("42501");
  });

  it("forms and submissions are for admins: members see none and cannot create or change them", async () => {
    await asUser(member.id, async (q) => {
      expect(await count(q, "select 1 from public.forms where organization_id = $1", [org])).toBe(0);
      expect(await count(q, "select 1 from public.form_submissions where organization_id = $1", [org])).toBe(0);
      expect((await q("update public.forms set name = 'x' where organization_id = $1", [org])).rowCount).toBe(0);
      expect((await q("delete from public.forms where organization_id = $1", [org])).rowCount).toBe(0);
    });
    const insert = await pgError(asUser(member.id, (q) => q("insert into public.forms (organization_id, name) values ($1, 'x')", [org])));
    expect(insert.code).toBe("42501");
    const submissions = await pgError(asUser(owner.id, (q) => q("delete from public.form_submissions where organization_id = $1", [org])));
    expect(submissions.code).toBe("42501");
  });

  it("a read-only or suspended organization keeps taking leads; a cancelled one takes none", async () => {
    // owner's decisions of 8 and 13 October 2026 (BIL-09): forms keep working in the background until payment
    for (const [state, phone] of [["read_only", "050-1234561"], ["suspended", "050-1234562"]]) {
      await asAdmin((q) => q("update public.organizations set status = $1 where id = $2", [state, org]));
      expect((await submit(form.token, { full_name: `ליד ${state}`, phone })).status, state).toBe("accepted");
    }
    await asAdmin((q) => q("update public.organizations set status = 'cancelled' where id = $1", [org]));
    const err = await pgError(submit(form.token, { full_name: "x", phone: "050-1234567" }));
    expect(err.hint).toBe("org:read_only");
    await asAdmin((q) => q("update public.organizations set status = 'trial' where id = $1", [org]));
  });

  it("plan rules: the free plan has one web form and no webhooks", async () => {
    const freeOwner = await createUser("free");
    const freeOrg = await createOrg(freeOwner.id, "עסק חינמי");
    await asAdmin((q) => q("update public.subscriptions set plan_key = 'free', status = 'active' where organization_id = $1", [freeOrg]));
    await asUser(freeOwner.id, (q) => q("insert into public.forms (organization_id, name) values ($1, 'טופס ראשון')", [freeOrg]));
    const second = await pgError(asUser(freeOwner.id, (q) => q("insert into public.forms (organization_id, name) values ($1, 'טופס שני')", [freeOrg])));
    expect(second.hint).toBe("limit:max_forms");
    const hook = await pgError(
      asUser(freeOwner.id, (q) => q("insert into public.forms (organization_id, kind, name) values ($1, 'webhook', 'x')", [freeOrg])),
    );
    expect(hook.hint).toBe("feature:api");
  });
});
