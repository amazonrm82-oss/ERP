// The legal documents, as empty frames. The wording is the owner's and their
// lawyer's (docs/DECISIONS.md): every page says it is a draft, lists what each
// section must cover, and the facts about the product that the lawyer needs.
// When a final text arrives, it replaces `sections` and `draft` becomes false.

export type LegalSection = {
  heading: string;
  /** What this section must say. For the lawyer, not the reader. */
  covers: string[];
  /** True facts about the product today, to build the wording on. */
  facts?: string[];
};

export type LegalDocument = {
  slug: string;
  title: string;
  purpose: string;
  draft: boolean;
  sections: LegalSection[];
};

